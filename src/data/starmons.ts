export function getBaseMultiplierForOrbs(count: number): number {
  if (count <= 3) return 1.0;
  if (count === 4) return 1.15;
  if (count === 5) return 1.25;
  if (count === 6) return 1.5;
  if (count === 7) return 1.65;
  if (count >= 8 && count <= 10) return 1.8;
  return 2.0;
}

export function getElementDisplayName(elem: ElementType, secondary?: ElementType, id?: string): string {
  const getSingleName = (e: ElementType) => {
    if (e === 'Metal') return id === 'moltenback' || id === 'dreadhorn' ? 'Steel' : 'Metal';
    return e;
  };

  if (secondary) {
    return `${getSingleName(elem)} & ${getSingleName(secondary)}`;
  }
  return getSingleName(elem);
}

