// Level Scaling Formulas
export function getCardsNeededForLevel(level: number): number {
  if (level <= 1) return 5;
  if (level === 2) return 15;
  if (level === 3) return 30;
  if (level === 4) return 50;
  if (level === 5) return 80;
  return Math.floor(25 * Math.pow(1.35, level));
}

export function getGoldNeededForLevel(level: number): number {
  if (level <= 1) return 200;
  if (level === 2) return 600;
  if (level === 3) return 1200;
  if (level === 4) return 2200;
  if (level === 5) return 3800;
  return Math.floor(1000 * Math.pow(1.5, level));
}

